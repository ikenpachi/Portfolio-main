// Bundle this project's small native ES modules into a classic script.
// This keeps the source modular and also supports VS Code's file:// launch.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const modules = new Map();
const output = [];
const importPattern = /^import\s+([A-Za-z_$][\w$]*)\s+from\s+["'](\.[^"']+)["'];?\s*$/gm;

async function compile(file) {
  if (modules.has(file)) return modules.get(file);
  const id = `module${modules.size}`;
  modules.set(file, id);
  let source = await readFile(file, 'utf8');
  const imports = [...source.matchAll(importPattern)];
  for (const match of imports) {
    const dependency = await compile(path.resolve(path.dirname(file), match[2]));
    source = source.replace(match[0], `const ${match[1]} = ${dependency}.default;`);
  }
  const exports = [];
  const namedDefault = source.match(/export default function\s+(\w+)/);
  if (namedDefault) {
    source = source.replace('export default function', 'function');
    exports.push(`default: ${namedDefault[1]}`);
  } else if (/export default\s/.test(source)) {
    source = source.replace(/export default\s/, 'const defaultExport = ');
    exports.push('default: defaultExport');
  }
  source = source.replace(/export (class|function)\s+(\w+)/g, (_, kind, name) => {
    exports.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*(import|export)\s/m.test(source)) throw new Error(`Unsupported module syntax: ${file}`);
  output.push(`// ${path.relative(root, file).replaceAll('\\', '/')}\nconst ${id} = (() => {\n${source.trim()}\nreturn { ${exports.join(', ')} };\n})();`);
  return id;
}

await compile(path.join(root, 'js/main.js'));
const bundle = `// Generated by node scripts/build.mjs. Edit js/main.js or js/modules/*.js.\n(() => {\n'use strict';\n${output.join('\n\n')}\n})();\n`.replace(/[\t ]+$/gm, '');
await writeFile(path.join(root, 'js/script.js'), bundle, 'utf8');
// Refresh asset URLs so a previously cached module entry cannot be loaded
// as the new classic script after deployment.
const revision = content => createHash('sha256').update(content).digest('hex').slice(0, 12);
const styles = await Promise.all(['styles.css', 'menu-mobile.css', 'experience.css'].map(file => readFile(path.join(root, 'css', file), 'utf8')));
const htmlPath = path.join(root, 'index.html');
const html = (await readFile(htmlPath, 'utf8'))
  .replace(/(src="\.\/js\/script\.js)(?:\?[^"\s]*)?"/, `$1?v=${revision(bundle)}"`)
  .replace(/(href="\.\/css\/styles\.css)(?:\?[^"\s]*)?"/, `$1?v=${revision(styles.join('\n'))}"`);
await writeFile(htmlPath, html, 'utf8');
console.log(`Built js/script.js: ${modules.size} modules, ${Buffer.byteLength(bundle)} bytes`);
